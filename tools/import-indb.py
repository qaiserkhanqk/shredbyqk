#!/usr/bin/env python3
"""Build js/foods-indb.js from the Indian Nutrient Databank (INDB).

INDB: 1,014 standard Indian recipes with nutrients per 100 g and per serving, derived from the
ICMR-NIN Indian Food Composition Tables 2017 with UK and USDA gap-fills.
  Indian Nutrient Databank (INDB). Current Developments in Nutrition 2024 (PMC11277795).
  https://github.com/lindsayjaacks/Indian-Nutrient-Databank-INDB-

Usage:
  git clone --depth 1 https://github.com/lindsayjaacks/Indian-Nutrient-Databank-INDB-.git /tmp/indb
  python3 tools/import-indb.py /tmp/indb/INDB.xlsx

Kept per recipe: code, name, kcal / protein / carbs / fat / fibre per 100 g, serving unit and
serving weight in grams (serving kcal / kcal per 100 g). Recipes that are deep fried are flagged:
INDB counts all the frying oil as eaten, so their values are far too high (a potato samosa comes
out at 577 kcal per 100 g). The app shows those with a warning and points to its own fried-food model.
"""
import json, re, sys
import pandas as pd

src = sys.argv[1] if len(sys.argv) > 1 else '/tmp/indb/INDB.xlsx'
x = pd.read_excel(src)

FRIED = re.compile(r'pakora|pakoda|samosa|vada|bhajji|bhaji|kachori|puri|poori|bhatura|pakodi|fritter|'
                   r'cutlet|chips|fried|fries|jalebi|gulab jamun|mathri|namak para|shakarpara|bonda|tikki|'
                   r'kebab|croquette|doughnut|imarti|balushahi|chakli|murukku|sev|bhujia|papdi', re.I)

def r1(v):
    try:
        v = float(v)
    except (TypeError, ValueError):
        return 0
    return 0 if v != v else round(v, 1)

rows = []
for _, r in x.iterrows():
    kcal = r1(r.energy_kcal)
    if kcal <= 0:
        continue
    sk = r1(r.unit_serving_energy_kcal)
    grams = round(sk / kcal * 100) if sk > 0 else 0
    name = re.sub(r'\s+', ' ', str(r.food_name)).strip()
    fat = r1(r.fat_g)
    # Flag only when the fat level backs it up: some names match ("sev tamatar") but aren't deep fried.
    fried = bool(FRIED.search(name)) and fat >= 18
    rows.append([str(r.food_code), name, kcal, r1(r.protein_g), r1(r.carb_g), fat, r1(r.fibre_g),
                 str(r.servings_unit or '').strip() if str(r.servings_unit) != 'nan' else '', grams, 1 if fried else 0])

head = ('// GENERATED by tools/import-indb.py from the Indian Nutrient Databank (INDB). Do not edit by hand.\n'
        '// Source: INDB, Current Developments in Nutrition 2024 (PMC11277795); github.com/lindsayjaacks/Indian-Nutrient-Databank-INDB-\n'
        '// Values derive from ICMR-NIN IFCT 2017. Row: [code, name, kcal, protein, carbs, fat, fibre (per 100 g),\n'
        '//   serving unit, serving grams, fried flag: INDB counts all frying oil as eaten, so these read high].\n')
out = head + 'export const INDB = ' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')).replace('],[', '],\n[') + ';\n'
open('js/foods-indb.js', 'w', encoding='utf-8').write(out)
print(len(rows), 'recipes,', sum(r[-1] for r in rows), 'flagged fried')
