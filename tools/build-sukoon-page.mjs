// Builds prototype/sukoon.html: the Sukoon calm session as one self-contained page (no server, no build step),
// for sharing or trying on a phone before the full app is deployed. Run: node tools/build-sukoon-page.mjs
// Pages that block outside audio (such as Claude artifacts) open the recitation on Quran.com instead.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url).pathname;
const read = f => readFileSync(root + f, 'utf8');
const between = (s, a, b) => { const i = s.indexOf(a), j = s.indexOf(b, i); if (i < 0 || j < 0) throw new Error(`markers not found: ${a}`); return s.slice(i, j); };

const html = read('index.html');
const screen = between(html, '<!-- SUKOON (calm) -->', '<!-- TESTS -->')
  .replace(/\s*<button type="button" class="back" data-back>.*?<\/button>/, '')
  .replace('<section class="screen" id="calm">', '<section class="screen on" id="calm">');
const live = between(html, '<!-- Sukoon live session -->', '<!-- Welcome -->').replace(between(html, '<!-- Alertness test -->', '<!-- Welcome -->'), '');
const css = read('css/styles.css');
const js = [read('js/hr.js'), read('js/sukoon.js'), read('js/vitals.js'), read('js/calm.js')].join('\n')
  .replace(/^import .*$/gm, '').replace(/^export /gm, '');
if (/\bimport\b.*from/.test(js)) throw new Error('unresolved import left in bundle');

const page = `<title>Sukoon</title>
<meta name="claude:viewport-fit-sides" content="cover">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,400..900&family=Figtree:wght@400;500;600;700&family=IBM+Plex+Mono:wght@500;600&display=swap" rel="stylesheet">
<style>
${css}
/* Standalone page: no tab bar, so less bottom padding */
.app { padding-block: 16px 48px; }
.page-head { margin-top: 4px; }
</style>
<!-- Generated by tools/build-sukoon-page.mjs from index.html, css/styles.css, js/sukoon.js and js/calm.js. Edit those, then rebuild. -->
<div class="stage-bg"></div>
<div class="app">
  <header class="topbar"><div class="wordmark"><i>SHRED</i><small>by QK</small></div></header>
  ${screen}
</div>
${live}
<div class="toast" id="toast" hidden></div>
<script type="module">
${js}
const KEY = 'shred_sukoon_v1';
let S = {};
try { S = JSON.parse(localStorage.getItem(KEY) || '{}'); } catch {}
const persist = () => { try { localStorage.setItem(KEY, JSON.stringify({ calm: S.calm, calmPrefs: S.calmPrefs })); } catch {} };
let tt;
const toast = m => { const t = document.querySelector('#toast'); t.textContent = m; t.hidden = false; clearTimeout(tt); tt = setTimeout(() => t.hidden = true, 2600); };
// Detect pages that block outside audio: a blocked file never plays, so link out instead.
const linkOnly = /claude\\.ai|claudeusercontent|claude\\.site/.test(location.host + document.referrer);
initCalm({ S, persist, toast, linkOnly });
renderCalm();
</script>
`;
writeFileSync(root + 'prototype/sukoon.html', page);
console.log(`prototype/sukoon.html  ${(page.length / 1024).toFixed(0)} KB`);
