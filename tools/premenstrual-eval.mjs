// Synthetic evaluation of premenstrual pattern detection: the new backward rule (js/cycle/premenstrual.js) against the
// older forward pattern finder (js/cycle/patterns.js), on the SAME synthetic people.
//   node tools/premenstrual-eval.mjs [people per group=1500] [seed=20261127]
// Two groups of synthetic people, 6 complete cycles each, one symptom (strong cravings):
//   • no pattern: strong cravings on random days at her own background rate, unrelated to her cycle;
//   • pattern: the same, plus a higher chance of strong cravings in the 5 days before each period.
// Measured: how often each method reports a cravings pattern (false patterns in group 1, detected patterns in group 2).
// EVERY generator setting below is an ASSUMPTION chosen to be plausible and varied; none is a measured population value.
// This shows how the rules behave, not how accurate they are for real people.
import * as M from '../js/cycle/model.js';
import { addDays } from '../js/cycle/dates.js';
import { premenstrualPatterns } from '../js/cycle/premenstrual.js';
import { findPatterns } from '../js/cycle/patterns.js';

export const ASSUMPTIONS = Object.freeze({
  CYCLES: 6, MEAN_LENGTH: [25, 33], CYCLE_SD: [1, 6], BACKGROUND: [0.03, 0.25], PREMENSTRUAL: [0.5, 0.9], LOGGING: [0.4, 0.95], PRE_DAYS: 5,
  note: 'All ranges are assumptions (uniform draws per person), not measured values.',
});

function rng(seed) { let a = seed >>> 0; return () => { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const uni = (r, [a, b]) => a + (b - a) * r();
const normal = r => Math.sqrt(-2 * Math.log(r() || 1e-12)) * Math.cos(2 * Math.PI * r());

export function syntheticPerson(r, hasPattern, A = ASSUMPTIONS) {
  const s = M.blankState('synthetic'); M.giveConsent(s, '2026-01-01T00:00:00.000Z'); M.setCategory(s, 'cravings', true);
  const mean = uni(r, A.MEAN_LENGTH), sd = uni(r, A.CYCLE_SD), bg = uni(r, A.BACKGROUND), pm = uni(r, A.PREMENSTRUAL), logP = uni(r, A.LOGGING);
  const starts = ['2025-01-06'];
  for (let i = 0; i < A.CYCLES; i++) starts.push(addDays(starts.at(-1), Math.max(18, Math.min(45, Math.round(mean + sd * normal(r))))));
  for (const st of starts) M.logPeriodStart(s, st, { today: '2027-12-31' });
  for (let i = 0; i + 1 < starts.length; i++) {
    for (let d = starts[i]; d < starts[i + 1]; d = addDays(d, 1)) {
      if (r() > logP) continue; // not logged that day
      const pre = d >= addDays(starts[i + 1], -A.PRE_DAYS);
      const strong = r() < (hasPattern && pre ? Math.max(bg, pm) : bg);
      M.logDay(s, d, { cravings: strong ? 'strong' : 'none' }, { today: '2027-12-31' });
    }
  }
  return { s, today: starts.at(-1), pm, logP };
}

const wilson = (k, n) => { if (!n) return [0, 0]; const z = 1.96, p = k / n, d = 1 + z * z / n, c = p + z * z / (2 * n), h = z * Math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)); return [(c - h) / d, (c + h) / d]; };
const pct = x => `${(100 * x).toFixed(1)}%`;

export function evaluate(n = 1500, seed = 20261127) {
  const r = rng(seed), out = {};
  for (const [group, hasPattern] of [['noPattern', false], ['pattern', true]]) {
    let newer = 0, older = 0, cpass = 0, clearN = 0, clearCpass = 0, clearOlder = 0;
    for (let i = 0; i < n; i++) {
      const { s, today, pm, logP } = syntheticPerson(r, hasPattern);
      const a = premenstrualPatterns(s, today, { rule: 'acog' })?.patterns.some(p => p.category === 'cravings');
      const o = findPatterns(s).some(p => p.category === 'cravings');
      const c = premenstrualPatterns(s, today, { rule: 'cpass' })?.patterns.some(p => p.category === 'cravings');
      newer += a; older += o; cpass += c;
      if (hasPattern && pm >= 0.7 && logP >= 0.7) { clearN++; clearCpass += c; clearOlder += o; } // a clear pattern, logged most days
    }
    out[group] = { n, newer, older, cpass, newerCI: wilson(newer, n), olderCI: wilson(older, n), cpassCI: wilson(cpass, n), clearN, clearCpass, clearOlder };
  }
  return out;
}

